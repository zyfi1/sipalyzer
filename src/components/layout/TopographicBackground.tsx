function toPath(points: Array<[number, number]>, minLon: number, maxLon: number, minLat: number, maxLat: number) {
  if (points.length < 2) return "";
  const step = points.length > 80 ? 2 : 1;
  const reduced = points.filter((_, i) => i % step === 0 || i === points.length - 1);
  const mapPoint = ([lon, lat]: [number, number]) => {
    const x = ((lon - minLon) / (maxLon - minLon)) * W;
    const y = H - ((lat - minLat) / (maxLat - minLat)) * H;
    return [x, y] as const;
  };
  const [x0, y0] = mapPoint(reduced[0]!);
  let d = `M ${x0.toFixed(1)} ${y0.toFixed(1)}`;
  for (let i = 1; i < reduced.length; i++) {
    const [x, y] = mapPoint(reduced[i]!);
    d += ` L ${x.toFixed(1)} ${y.toFixed(1)}`;
  }
  return d;
}

export const TopographicBackground = memo(function TopographicBackground() {
  const paths = useMemo(() => {
    const all = STIRLING_CASTLE_CONTOURS.flatMap((c) => c.coords);
    const lons = all.map(([lon]) => lon);
    const lats = all.map(([, lat]) => lat);
    const minLon = Math.min(...lons) - 0.0008;
    const maxLon = Math.max(...lons) + 0.0008;
    const minLat = Math.min(...lats) - 0.0006;
    const maxLat = Math.max(...lats) + 0.0006;
    return STIRLING_CASTLE_CONTOURS.map((c) => ({
      d: toPath(c.coords, minLon, maxLon, minLat, maxLat),
      elevation: c.elevation,
    })).filter((p) => p.d.length > 0);
  }, []);

  return (
    <>
      <svg
        className="absolute inset-0 z-0 pointer-events-none"
        viewBox={`0 0 ${W} ${H}`}
        preserveAspectRatio="xMidYMid slice"
        fill="none"
        style={{ borderRadius: "inherit", width: "100%", height: "100%" }}
        aria-hidden="true"
      >
        {paths.map((p, i) => (
          <path
            key={i}
            d={p.d}
            stroke="hsl(var(--foreground))"
            strokeWidth={0.8}
            strokeOpacity={p.elevation >= 90 ? 0.09 : p.elevation >= 80 ? 0.075 : 0.065}
            fill="none"
          />
        ))}
      </svg>
      <div className="absolute bottom-3 right-3 z-0 font-mono text-[11px] tracking-wide text-foreground/20 pointer-events-none select-none">
        <span>{STIRLING_CASTLE_LAT.toFixed(6)}, {STIRLING_CASTLE_LON.toFixed(6)}</span>
      </div>
    </>
  );
});
